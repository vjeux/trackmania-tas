//! lamp's lighting draws include. The spot render (FUN_1402398f0 → FUN_14023b300) builds a CONE from the light instance
//! {position = entry+0x2c, axis = the Iso4's third column, cos(half angle) = light+0x118, R = light+0xa0[idx]} and calls
//! the batch builder FUN_14023ea90 over the record array (0x58-B records): a record is drawn iff its BOX is within R of the
//! light position (FUN_1402059b0, the closest-point distance) AND its BOUNDING SPHERE (centre, |half|) passes the cone test
//! FUN_1414016f0 (the classic sphere-vs-cone with the centre pushed by r/sin along the axis). No quality gate, no kind
//! filter (stpad lamp A: 50 records of q 1 … 0.25, verified 65/65 against the capture in `tests`). A BALL light
//! (FUN_14023c250 → FUN_14023cf20 → FUN_14023d190) uses the sphere test only.
use crate::geometry::LightDef;

/// FUN_141401680's cone: position, unit axis, cos and sin of the half angle, the radius.
#[derive(Clone, Copy, Debug)]
pub struct Cone {
    pub pos: [f32; 3],
    pub dir: [f32; 3],
    pub cos_half: f32,
    pub r: f32,
    pub sin_half: f32,
    pub inv_sin: f32,
}

impl Cone {
    pub fn new(pos: [f32; 3], dir: [f32; 3], cos_half: f32, r: f32) -> Cone {
        let sin_half = (1.0 - cos_half * cos_half).max(0.0).sqrt();
        Cone { pos, dir, cos_half, r, sin_half, inv_sin: 1.0 / sin_half }
    }
}

/// FUN_1402059b0: does the sphere (pos, r) reach the box (centre, half)? Per axis d = |pos − c| − half; inside when every d ≤ 0,
/// else Σ (positive d)² ≤ r².
pub fn box_in_sphere(centre: [f32; 3], half: [f32; 3], pos: [f32; 3], r: f32) -> bool {
    let d = [(pos[0] - centre[0]).abs() - half[0], (pos[1] - centre[1]).abs() - half[1], (pos[2] - centre[2]).abs() - half[2]];
    let mut s = 0.0f32;
    let mut outside = false;
    for v in d {
        if v > 0.0 {
            outside = true;
            s += v * v;
        }
    }
    !outside || r * r >= s
}

/// FUN_1414016f0: does the sphere (centre, radius) intersect the cone? Transcribed as compiled (the two branches by the
/// sign of cos_half; the second handles half angles ≥ 90°).
pub fn sphere_in_cone(cone: &Cone, centre: [f32; 3], radius: f32) -> bool {
    let c = cone.cos_half;
    let v = [centre[0] - cone.pos[0], centre[1] - cone.pos[1], centre[2] - cone.pos[2]];
    let f6 = radius * cone.inv_sin;
    let d = cone.dir;
    if c <= 0.0 {
        let p = [d[0] * f6 + v[0], d[1] * f6 + v[1], d[2] * f6 + v[2]];
        let f8 = -(p[1] * d[1] + p[0] * d[0] + p[2] * d[2]);
        if 0.0 < f8 && (p[0] * p[0] + p[1] * p[1] + p[2] * p[2]) * c * c <= f8 * f8 {
            return false;
        }
        let rr = radius + cone.r;
        !(rr * rr < v[0] * v[0] + v[1] * v[1] + v[2] * v[2])
    } else {
        let p = [d[0] * f6 + v[0], d[1] * f6 + v[1], d[2] * f6 + v[2]];
        let f7 = p[1] * d[1] + p[0] * d[0] + p[2] * d[2];
        if f7 <= 0.0 || f7 * f7 < (p[0] * p[0] + p[1] * p[1] + p[2] * p[2]) * c * c {
            return false;
        }
        let dist2 = v[0] * v[0] + v[1] * v[1] + v[2] * v[2];
        let f2 = -(d[1] * v[1] + d[0] * v[0] + d[2] * v[2]);
        let mut rr = radius;
        if f2 <= 0.0 || f2 * f2 < cone.sin_half * cone.sin_half * dist2 {
            rr += cone.r;
        }
        !(rr * rr < dist2)
    }
}

/// The record filter of one local light: `r_eff` = the instance radius the game reads (40.7077 for the RoadBorderSpot; its
/// file radius is 40 — see moods::att_hn2's doc), `light.cone.1` = the outer cone angle in degrees (ball lights: 180 → sphere
/// only).
pub fn local_light_sees(rec_centre: [f32; 3], rec_half: [f32; 3], light: &LightDef, r_eff: f32) -> bool {
    if !box_in_sphere(rec_centre, rec_half, light.pos, r_eff) {
        return false;
    }
    if light.cone.1 >= 180.0 {
        return true;
    }
    let cone = Cone::new(light.pos, light.dir, (light.cone.1.to_radians() * 0.5).cos(), r_eff);
    let br = (rec_half[0] * rec_half[0] + rec_half[1] * rec_half[1] + rec_half[2] * rec_half[2]).sqrt();
    sphere_in_cone(&cone, rec_centre, br)
}

